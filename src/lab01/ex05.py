# 1. Считываем строку с ФИО
raw_input = input("ФИО: ")

# 2. Разбиваем строку на слова, отсекая все лишние пробелы
words = raw_input.split()

# 3. Собираем инициалы: берем 0-й символ каждого слова,
# переводим в верхний регистр (.upper()) и добавляем точку в конце
initials = f"{words[0][0].upper()}{words[1][0].upper()}{words[2][0].upper()}."

# 4. Собираем строку обратно, соединяя слова ровно одним пробелом
clean_fio = " ".join(words)

# 5. Считаем длину полученной строки без лишних пробелов
length = len(clean_fio)

# 6. Выводим результат в точности по формату из методички
print(f"Инициалы: {initials}")
print(f"Длина (символов): {length}")